  on public.vault_lines
  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1 from public.vault_chapters c
      where c.id = chapter_id and c.user_id = (select auth.uid())
    )
