  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1 from public.vault_notebooks n
      where n.id = notebook_id and n.user_id = (select auth.uid())
    )
  );

drop policy if exists "Users manage their own vault_lines" on public.vault_lines;
